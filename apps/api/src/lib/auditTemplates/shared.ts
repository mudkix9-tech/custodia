const headerTranslations: Record<string, any> = {
  en: { generated: "Generated", confidential: "Confidential", generatedBy: "Generated by" },
  de: { generated: "Generiert", confidential: "Vertraulich", generatedBy: "Generiert von" },
  fr: { generated: "Généré", confidential: "Confidentiel", generatedBy: "Généré par" },
};

export function renderHeader(orgName: string, reportTitle: string, generatedAt: Date, logoUrl?: string, locale: string = 'en') {
  const t = headerTranslations[locale] || headerTranslations.en;
  return `
    <div class="header">
      <div>
        ${logoUrl ? `<div class="header-logo"><img src="${logoUrl}" alt="${orgName}" /></div>` : ''}
        <div class="title">${reportTitle}</div>
        <div class="subtitle">${orgName}</div>
      </div>
      <div class="header-meta">
        <div>${t.generated}: ${generatedAt.toISOString().split('T')[0]}</div>
        <div>${t.confidential}</div>
      </div>
    </div>
  `;
}

export function renderFooter(orgName: string, pageLabel: string, locale: string = 'en') {
  const t = headerTranslations[locale] || headerTranslations.en;
  return `
    <div class="footer">
      ${orgName} — ${pageLabel} — ${t.generatedBy} Privaro · ${new Date().toISOString().split('T')[0]}
    </div>
  `;
}

export function severityBadge(severity: string) {
  return `<span class="badge badge-${severity}">${severity.charAt(0).toUpperCase() + severity.slice(1)}</span>`;
}

export function dpaBadge(status: string) {
  const map: Record<string, string> = {
    signed: 'badge-signed',
    expired: 'badge-expired',
    not_started: 'badge-not-started',
    draft: 'badge-not-started',
    sent: 'badge-medium',
  };
  return `<span class="badge ${map[status] || 'badge-not-started'}">${status.replace('_', ' ')}</span>`;
}

export function wrapPage(content: string) {
  return `
    <!DOCTYPE html>
    <html>
    <head><meta charset="utf-8" />${STYLES}</head>
    <body><div class="page">${content}</div></body>
    </html>
  `;
}

export function escapeHtml(str: string | null | undefined): string {
  if (!str) return '';
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export function formatDate(d: Date | string | null | undefined): string {
  if (!d) return '—';
  const date = typeof d === 'string' ? new Date(d) : d;
  return date.toISOString().split('T')[0] || '—';
}